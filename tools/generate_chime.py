"""Regenerate the flash-resident 44.1 kHz mono ding-dong and a listening preview."""
from pathlib import Path
import math
import struct
import wave

root = Path(__file__).resolve().parents[1]
rate = 44100
samples = []
for n in range(int(rate * 2.4)):
    t = n / rate
    value = 0.0
    for start, freq, duration in [(0.10, 880.0, 0.90), (0.85, 659.255, 1.45)]:
        local = t - start
        if 0 <= local < duration:
            attack = min(1.0, local / 0.008)
            release = min(1.0, (duration - local) / 0.06)
            envelope = attack * release * math.exp(-3.5 * local)
            value += envelope * (math.sin(2 * math.pi * freq * local)
                                  + 0.20 * math.sin(2 * math.pi * freq * 2 * local))
    samples.append(round(max(-1.0, min(1.0, value * 0.45)) * 32767))

lines = ["#pragma once", "#include <cstddef>", "#include <cstdint>",
         "// Generated by tools/generate_chime.py; PCM lives in flash on ESP32.",
         "static const int16_t CHIME_PCM[] = {"]
for i in range(0, len(samples), 20):
    lines.append("  " + ",".join(map(str, samples[i:i+20])) + ",")
lines += ["};", "constexpr size_t CHIME_SAMPLES = sizeof(CHIME_PCM) / sizeof(CHIME_PCM[0]);", ""]
(root / "components/kallsup_chime/chime_pcm.h").write_text("\n".join(lines))
with wave.open(str(root / "dingdong-preview.wav"), "wb") as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(rate)
    w.writeframes(b"".join(struct.pack("<h", s) for s in samples))
print(f"Generated {len(samples)} samples, {len(samples)/rate:.1f} seconds")
